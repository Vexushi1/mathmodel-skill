def prior_r3_text(relative, text):
    """Restore registered blocks while retaining every unrelated character."""
    for current, previous in R3_APPROVED_REWRITES.get(relative, ()):
        if not current or text.count(current) != 1:
            raise ValueError(f"R3 source block is missing or duplicated: {relative}")
        text = text.replace(current, previous, 1)
    return text


def prior_r3_bytes(relative, raw):
    """Verify both complete source identities before returning R2 bytes."""
    identity = R3_SOURCE_IDENTITIES.get(relative)
    if identity is None:
        return raw
    prior_sha, current_sha = identity
    if hashlib.sha256(raw).hexdigest() != current_sha:
        raise ValueError(f"R3 source bytes changed: {relative}")
    previous = prior_r3_text(relative, raw.decode("utf-8")).encode("utf-8")
    if hashlib.sha256(previous).hexdigest() != prior_sha:
        raise ValueError(f"R3 predecessor bytes differ: {relative}")
    return previous


def prior_r3_schema(schema):
    """Restore only E24's paper-source description from the current schema."""
    previous = deepcopy(schema)
    paper_source = previous["$defs"]["claim_consumption_policy"]["properties"]["paper_source"]
    expected = "1.5.0项目显式选择的唯一论文载体与入口。"
    if paper_source.get("description") != expected:
        raise AssertionError("R3 schema inverse rejected unapproved paper_source description")
    paper_source["description"] = (
        "1.5.0项目显式选择的唯一论文载体；只声明载体与入口，不复制正文或数值事实。"
    )
    return previous
